CREATE TABLE IF NOT EXISTS lineas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR(10) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  zona VARCHAR(80) NOT NULL,
  descripcion TEXT NOT NULL,
  color VARCHAR(20) NOT NULL DEFAULT '#16a34a'
);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'PASAJERO' CHECK (rol IN ('ADMIN', 'CONDUCTOR', 'PASAJERO')),
  nombre_completo VARCHAR(120),
  categoria VARCHAR(20) NOT NULL DEFAULT 'GENERAL' CHECK (categoria IN ('GENERAL', 'ESCOLAR', 'UNIVERSITARIO', 'ADULTO_MAYOR')),
  codigo_rude VARCHAR(30),
  cod_est VARCHAR(30),
  email_upds VARCHAR(100),
  foto_credencial_url TEXT,
  estudiante_validado BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS tarifas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria VARCHAR(20) NOT NULL UNIQUE CHECK (categoria IN ('GENERAL', 'ESCOLAR', 'UNIVERSITARIO', 'ADULTO_MAYOR')),
  monto NUMERIC(4,2) NOT NULL CHECK (monto >= 0),
  descripcion VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS micros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR(20) NOT NULL UNIQUE,
  interno VARCHAR(20) NOT NULL UNIQUE,
  capacidad INTEGER NOT NULL CHECK (capacidad BETWEEN 18 AND 25),
  pasajeros_actuales INTEGER NOT NULL DEFAULT 0 CHECK (pasajeros_actuales >= 0 AND pasajeros_actuales <= capacidad),
  estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'MANTENIMIENTO', 'INACTIVO', 'EMERGENCIA')),
  linea_id INTEGER NOT NULL REFERENCES lineas(id),
  conductor_id INTEGER REFERENCES usuarios(id),
  latitud DECIMAL(10, 8) NOT NULL DEFAULT -17.7833,
  longitud DECIMAL(11, 8) NOT NULL DEFAULT -63.1821,
  ultima_actualizacion_geo TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pagos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  micro_id INTEGER NOT NULL REFERENCES micros(id),
  monto NUMERIC(4,2) NOT NULL,
  metodo VARCHAR(30) NOT NULL DEFAULT 'TARJETA_CREDITO',
  codigo_ticket VARCHAR(40) NOT NULL UNIQUE,
  estado VARCHAR(20) NOT NULL DEFAULT 'EXITOSO' CHECK (estado IN ('EXITOSO', 'FALLIDO', 'PENDIENTE')),
  es_trasbordo_gratuito BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS trasbordos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  micro_origen_id INTEGER NOT NULL REFERENCES micros(id),
  micro_destino_id INTEGER NOT NULL REFERENCES micros(id),
  motivo VARCHAR(30) NOT NULL CHECK (motivo IN ('CAMBIO_TURNO', 'FALLA_MECANICA', 'EMERGENCIA')),
  cantidad_pasajeros INTEGER NOT NULL DEFAULT 0,
  estado VARCHAR(20) NOT NULL DEFAULT 'COMPLETADO' CHECK (estado IN ('SOLICITADO', 'EN_PROCESO', 'COMPLETADO', 'CANCELADO')),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notificaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER REFERENCES usuarios(id),
  micro_id INTEGER REFERENCES micros(id),
  titulo VARCHAR(100) NOT NULL,
  mensaje TEXT NOT NULL,
  tipo VARCHAR(30) NOT NULL DEFAULT 'INFO' CHECK (tipo IN ('INFO', 'EMERGENCIA', 'TRASBORDO')),
  leido BOOLEAN NOT NULL DEFAULT FALSE,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

